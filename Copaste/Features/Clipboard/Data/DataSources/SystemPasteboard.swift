import Foundation
import UniformTypeIdentifiers
import AppKit

/// What Copaste puts back on the clipboard.
nonisolated enum PasteboardPayload: Sendable {
    case text(String)
    /// Text in a monospaced font, as rich text and HTML for apps that take them and plain text for the rest.
    case monospaced(String)
    case image(URL)
    /// An image made in Copaste that isn't saved anywhere.
    case png(Data)
    case files([URL])
    /// Several entries, each its own clipboard item.
    indirect case many([PasteboardPayload])
}

/// The system clipboard, watched for changes.
final class SystemPasteboard {
    /// Markers apps such as password managers set on secrets and throwaway data (nspasteboard.org).
    nonisolated private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]

    /// Set on items that arrived from an iPhone, iPad or another Mac through Universal Clipboard.
    nonisolated static let universalClipboardType = NSPasteboard.PasteboardType("com.apple.is-remote-clipboard")

    var onCapture: ((Capture) -> Void)?
    /// Whether to save Universal Clipboard items as they arrive (Settings).
    var savesUniversalClipboard: () -> Bool = { true }
    private let pasteboard: NSPasteboard
    private var changeCount: Int

    /// Tests pass a private pasteboard so they never touch what the user copied.
    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        changeCount = pasteboard.changeCount
    }
    private var timer: Timer?

    func startMonitoring() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: Metrics.Clipboard.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = Metrics.Clipboard.pollTolerance
    }

    /// Records a copy made since the last check right away, instead of on the next tick (which macOS may delay while
    /// Copaste is in the background). For when the history must be current, e.g. as a window opens.
    func checkNow() {
        poll()
    }

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        if pasteboard.types?.contains(Self.universalClipboardType) == true {
            return captureUniversalClipboard()
        }
        guard let content = Self.read(pasteboard) else { return }
        let app = NSWorkspace.shared.frontmostApplication
        onCapture?(Capture(content: content, sourceName: app?.localizedName, sourceBundleID: app?.bundleIdentifier))
    }

    /// Universal Clipboard only advertises the item; reading it downloads it from the other device, which can take
    /// a while for photos, so it's read off the main actor. Skipped if something else was copied meanwhile.
    private func captureUniversalClipboard() {
        guard savesUniversalClipboard() else { return }
        let name = pasteboard.name
        let change = changeCount
        Task {
            guard let content = await Self.readInBackground(name), change == changeCount else { return }
            onCapture?(Capture(content: content, sourceName: L(.universalClipboardSource)))
        }
    }

    @concurrent
    nonisolated private static func readInBackground(_ name: NSPasteboard.Name) async -> CapturedContent? {
        read(NSPasteboard(name: name))
    }

    nonisolated private static func read(_ pasteboard: NSPasteboard) -> CapturedContent? {
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: privateTypes) else { return nil }
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return .files(urls.map(Self.clipFile))
        }
        // ponytail: text wins over an image when both are offered (spreadsheets copy both); revisit if image-first apps miss out.
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(string)
        }
        // Screenshots and most apps offer PNG already: keep it as is instead of decoding and re-encoding it.
        if let png = pasteboard.data(forType: .png), let rep = NSBitmapImageRep(data: png) {
            return .image(png: png, width: rep.pixelsWide, height: rep.pixelsHigh)
        }
        if let image = NSImage(pasteboard: pasteboard), let png = image.pngRepresentation {
            let size = image.pixelSize
            return .image(png: png, width: Int(size.width), height: Int(size.height))
        }
        if let color = NSColor(from: pasteboard)?.usingColorSpace(.sRGB) {
            let value = ColorValue(red: color.redComponent, green: color.greenComponent,
                                   blue: color.blueComponent, alpha: color.alphaComponent)
            return .text(value.hex)
        }
        return nil
    }

    func write(_ payload: PasteboardPayload) {
        pasteboard.clearContents()
        pasteboard.writeObjects(Self.objects(payload))
        // Our own write isn't a new copy.
        changeCount = pasteboard.changeCount
    }

    private static func objects(_ payload: PasteboardPayload) -> [any NSPasteboardWriting] {
        switch payload {
        case let .text(text): [text as NSString]
        case let .monospaced(text): [monospacedItem(text)]
        case let .image(url): NSImage(contentsOf: url).map { [$0] } ?? []
        case let .png(data): NSImage(data: data).map { [$0] } ?? []
        case let .files(urls): urls.map { $0 as NSURL }
        case let .many(payloads): payloads.flatMap(objects)
        }
    }

    private static func monospacedItem(_ text: String) -> NSPasteboardItem {
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        let size = Metrics.PasteSpecial.codeFontSize
        let font = NSFont(name: "Menlo", size: size) ?? .monospacedSystemFont(ofSize: size, weight: .regular)
        let rich = NSAttributedString(string: text, attributes: [.font: font])
        if let rtf = rich.rtf(from: NSRange(location: 0, length: rich.length)) { item.setData(rtf, forType: .rtf) }
        let escaped = text.replacing("&", with: "&amp;").replacing("<", with: "&lt;").replacing(">", with: "&gt;")
        item.setString("<pre><code>\(escaped)</code></pre>", forType: .html)
        return item
    }

    nonisolated private static func clipFile(_ url: URL) -> ClipFile {
        let size = (try? url.resourceValues(forKeys: [.fileSizeKey]))?.fileSize.map(Int64.init)
        return ClipFile(path: url.path, name: url.lastPathComponent, size: size)
    }
}
